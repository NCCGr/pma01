#!/usr/bin/env node
// Generates src/sql-parser/contexts/*.ts and src/sql-parser/locale/translations.ts from the vendored phpmyadmin/sql-parser.
// Usage: node scripts/sql-parser-generate.ts [path/to/sql-parser]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vendor = path.resolve(process.argv[2] ?? path.join(root, 'vendor/phpmyadmin-5.2.3/vendor/sql-parser'));
const outContexts = path.join(root, 'src/sql-parser/contexts');
const outLocale = path.join(root, 'src/sql-parser/locale');

const FLAGS: Record<string, number> = {
	FLAG_KEYWORD: 1,
	FLAG_KEYWORD_RESERVED: 2,
	FLAG_KEYWORD_COMPOSED: 4,
	FLAG_KEYWORD_DATA_TYPE: 8,
	FLAG_KEYWORD_KEY: 16,
	FLAG_KEYWORD_FUNCTION: 32,
};

// The default sort order (UTF-16 code units), written out for the linter.
const byCodeUnit = (left: string, right: string) => (left < right ? -1 : Number(left > right));

/** A single-quoted TypeScript string literal, as the linter wants it. */
function quote(value: string) {
	return `'${value.replaceAll('\\', '\\\\').replaceAll('\'', String.raw`\'`).replaceAll('\n', String.raw`\n`)
		.replaceAll('\r', String.raw`\r`)}'`;
}

const header = '// Generated by scripts/sql-parser-generate.ts from phpmyadmin/sql-parser; do not edit.\n';

function parseContext(file: string) {
	const source = fs.readFileSync(file, 'utf8');
	const keywords = new Map<string, number>();
	for (const match of source.matchAll(/^\s+'([^']+)' => ([^,\n]+),$/gm)) {
		let flags = 0;
		for (const part of match[2].split('|')) {
			const name = part.trim().replace(/^Token::/, '');
			if (!(name in FLAGS)) {
				throw new Error(`Unknown flag ${name} in ${file}`);
			}
			flags |= FLAGS[name];
		}
		// PHP keeps the last value of a duplicated key, and so does Map.set().
		keywords.set(match[1], flags);
	}
	if (keywords.size === 0) {
		throw new Error(`No keywords found in ${file}`);
	}
	return keywords;
}

function writeContexts() {
	fs.mkdirSync(outContexts, { recursive: true });
	const names = fs.readdirSync(path.join(vendor, 'src/Contexts'))
		.filter(file => /^Context\w+\.php$/.test(file))
		.map(file => file.slice('Context'.length, -'.php'.length))
		.toSorted(byCodeUnit);
	for (const name of names) {
		const keywords = parseContext(path.join(vendor, 'src/Contexts', `Context${name}.php`));
		const byFlags = new Map<number, string[]>();
		for (const [keyword, flags] of keywords) {
			const list = byFlags.get(flags);
			if (list) {
				list.push(keyword);
			} else {
				byFlags.set(flags, [keyword]);
			}
		}
		const lines = [...byFlags].map(([flags, list]) => `\t${flags}: '${list.join(',')}',`);
		fs.writeFileSync(path.join(outContexts, `${name}.ts`), `${header}export default {\n${lines.join('\n')}\n} satisfies Record<number, string>;\n`);
	}
	const imports = names.map(name => `import ${name} from './${name}.ts';`).join('\n');
	const entries = names.map(name => `\t${name},`).join('\n');
	fs.writeFileSync(path.join(outContexts, 'index.ts'), `${header}${imports}\n\n/** Keywords of every context, grouped by their Token::FLAG_* bits and comma separated. */\nexport const CONTEXT_KEYWORDS: Record<string, Record<number, string>> = {\n${entries}\n};\n`);
	return names.length;
}

function readMo(file: string) {
	const buffer = fs.readFileSync(file);
	let read: (offset: number) => number;
	if (buffer.readUInt32LE(0) === 0x95_04_12_DE) {
		read = offset => buffer.readUInt32LE(offset);
	} else if (buffer.readUInt32BE(0) === 0x95_04_12_DE) {
		read = offset => buffer.readUInt32BE(offset);
	} else {
		throw new Error(`Not a .mo file: ${file}`);
	}
	const count = read(8);
	const originals = read(12);
	const translations = read(16);
	const entries = new Map<string, string>();
	for (let index = 0; index < count; index++) {
		const idLength = read(originals + index * 8);
		const idOffset = read(originals + index * 8 + 4);
		const strLength = read(translations + index * 8);
		const strOffset = read(translations + index * 8 + 4);
		const id = buffer.toString('utf8', idOffset, idOffset + idLength);
		// Skip the header entry and contexts; plural forms are not used by the parser.
		if (id === '' || id.includes('\u{4}')) {
			continue;
		}
		const str = buffer.toString('utf8', strOffset, strOffset + strLength);
		entries.set(id.split('\0', 1)[0], str.split('\0', 1)[0]);
	}
	return entries;
}

function writeTranslations() {
	fs.mkdirSync(outLocale, { recursive: true });
	const localeDir = path.join(vendor, 'locale');
	const locales = fs.readdirSync(localeDir).filter(name => fs.existsSync(path.join(localeDir, name, 'LC_MESSAGES/sqlparser.mo'))).toSorted(byCodeUnit);
	const perLocale = new Map(locales.map(locale => [locale, readMo(path.join(localeDir, locale, 'LC_MESSAGES/sqlparser.mo'))]));
	const messages = [...new Set(perLocale.values().flatMap(entries => entries.keys()))].toSorted(byCodeUnit);
	const table: Record<string, string[]> = {};
	for (const [locale, entries] of perLocale) {
		table[locale] = messages.map(message => entries.get(message) ?? '');
	}
	const messageLines = messages.map(message => `\t${quote(message)},`).join('\n');
	const localeLines = Object.entries(table).map(([locale, list]) => `\t${quote(locale)}: [${list.map(item => quote(item)).join(', ')}],`).join('\n');
	const body = `${header}/** Every msgid found in the sqlparser.mo catalogs. */\nexport const MESSAGES: string[] = [\n${messageLines}\n];\n\n/** Translations per locale, indexed like MESSAGES; an empty string means untranslated. */\nexport const TRANSLATIONS: Record<string, string[]> = {\n${localeLines}\n};\n`;
	fs.writeFileSync(path.join(outLocale, 'translations.ts'), body);
	return locales.length;
}

const contexts = writeContexts();
const locales = writeTranslations();
console.log(`Generated ${contexts} contexts and ${locales} locales from ${vendor}`);
