// Regenerates src/lib/pma/config-defaults.ts from libraries/config.default.php inside the oracle container.
// Usage: node scripts/generate-pma-config.ts (needs the dbadmin-pma Docker container running).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import process from 'node:process';

const CONTAINER = process.env.PMA_ORACLE_CONTAINER ?? 'dbadmin-pma';

// Only the shipped defaults are read; the container's own config.inc.php is never included, so no secrets are involved.
const php = String.raw`
define('ROOT_PATH', '/var/www/html/');
define('PHPMYADMIN', true);
require ROOT_PATH . 'libraries/constants.php';
$cfg = [];
include ROOT_PATH . 'libraries/config.default.php';
// Config::loadDefaults() reads Settings, which casts these transformation options to integers.
require AUTOLOAD_FILE;
$cfg['DefaultTransformations'] = (new PhpMyAdmin\Config\Settings([]))->toArray()['DefaultTransformations'];
$server = $cfg['Servers'][1];
unset($cfg['Servers']);
echo json_encode(['settings' => $cfg, 'server' => $server], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION);
`;

const output = execFileSync('docker', ['exec', CONTAINER, 'php', '-r', php], { encoding: 'utf8', env: { ...process.env, MSYS_NO_PATHCONV: '1' } });
const { settings, server } = JSON.parse(output);

const source = `// Generated by scripts/generate-pma-config.ts from phpMyAdmin 5.2.3 libraries/config.default.php; do not edit.
/* eslint-disable unicorn/text-encoding-identifier-case -- values such as "utf-8" are upstream settings, copied verbatim */

/** $cfg defaults, without $cfg['Servers']. */
export const configDefaults = ${JSON.stringify(settings, null, '\t')};

/** $cfg['Servers'][$i] defaults that Config::checkServers() merges into every configured server. */
export const serverDefaults = ${JSON.stringify(server, null, '\t')};
`;

writeFileSync(new URL('../src/lib/pma/config-defaults.ts', import.meta.url), source);
// JSON quoting and spacing differ from the house style, which ESLint can restore.
execFileSync(process.execPath, ['node_modules/eslint/bin/eslint.js', '--flag', 'unstable_native_nodejs_ts_config', '--fix', 'src/lib/pma/config-defaults.ts'], { cwd: new URL('..', import.meta.url), stdio: 'inherit' });
process.stdout.write('Wrote src/lib/pma/config-defaults.ts\n');
