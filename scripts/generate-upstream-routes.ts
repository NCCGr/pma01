// Regenerates src/server/pma/upstream-routes.ts from phpMyAdmin 5.2.3's libraries/routes.php.
// Usage: node scripts/generate-upstream-routes.ts <path-to-phpmyadmin>/libraries/routes.php
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(process.argv[2], 'utf8');
const prefixes = [];
const routes = [];
for (const line of source.split('\n')) {
	const group = /addGroup\('([^']*)'/.exec(line);
	if (group) {
		prefixes.push(group[1]);
		continue;
	}
	if (/^\s*\}\);/.test(line)) {
		prefixes.pop();
		continue;
	}
	const route = /->(get|post|addRoute)\((?:\[([^\]]*)\],\s*)?'([^']*)',\s*([\w\\]+)::class/.exec(line);
	if (!route) {
		continue;
	}
	const [, kind, methodList, path, controller] = route;
	let methods;
	if (kind === 'addRoute') {
		methods = methodList.split(',').map(method => method.trim().replaceAll('\'', ''));
	} else {
		methods = [kind.toUpperCase()];
	}
	routes.push({ methods, path: prefixes.join('') + path, controller: controller.replaceAll('\\', '/') });
}
if (prefixes.length > 0) {
	throw new Error(`Unbalanced route groups: ${prefixes.join(', ')}`);
}

const lines = routes.map(route => `\t{ methods: ${JSON.stringify(route.methods)}, path: ${JSON.stringify(route.path)}, controller: '${route.controller}' },`);
writeFileSync('src/server/pma/upstream-routes.ts', `// Generated by scripts/generate-upstream-routes.ts from phpMyAdmin 5.2.3 libraries/routes.php; do not edit by hand.
export interface UpstreamRoute {
\tmethods: string[];
\t/** FastRoute pattern: {name} placeholders and [optional] suffixes. */
\tpath: string;
\tcontroller: string;
}

export const upstreamRoutes: UpstreamRoute[] = [
${lines.join('\n')}
];
`);
console.log(`${routes.length} routes`);
