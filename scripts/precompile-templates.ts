// Parses every phpMyAdmin template into Twing ASTs at build time. Parsing must never happen in the Worker:
// twig-lexer unescapes string literals with `new Function`, which workerd forbids.
import {
	mkdirSync,
	readFileSync,
	readdirSync,
	writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { createPmaEnvironment } from '../src/server/twig/environment.ts';
import { createTemplateState } from '../src/server/twig/state.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const templatesDir = path.join(root, 'vendor/phpmyadmin-5.2.3/templates');
const themesDir = path.join(root, 'public/themes');
const outputDir = path.join(root, 'src/generated');

// Code-unit order rather than localeCompare, so the output does not depend on the machine's locale.
function compareCodeUnits(left: string, right: string) {
	if (left < right) {
		return -1;
	}
	if (left > right) {
		return 1;
	}
	return 0;
}

function listFiles(dir: string) {
	return readdirSync(dir, { recursive: true, withFileTypes: true })
		.filter(entry => entry.isFile())
		.map(entry => path.relative(dir, path.join(entry.parentPath, entry.name)).split(path.sep).join('/'))
		.toSorted(compareCodeUnits);
}

const names = listFiles(templatesDir).filter(name => name.endsWith('.twig'));
const sources = Object.fromEntries(names.map(name => [name, readFileSync(path.join(templatesDir, name), 'utf8')]));

const asts = new Map<string, unknown>();
const env = createPmaEnvironment({
	templates: sources,
	state: createTemplateState(),
	cache: {
		write: async (key, ast) => {
			asts.set(key, ast);
		},
		load: async () => null,
		getTimestamp: async () => 0,
	},
});
for (const name of names) {
	await env.loadTemplate(name);
}

// Positions only feed error messages and source maps, and dropping them shrinks the output by about a quarter.
const stripPositions = (key: string, value: unknown) => {
	if (key === 'line' || key === 'column' || (key === 'tag' && value === null)) {
		return;
	}
	return value;
};
const entries = names.map(name => `\t\t${JSON.stringify(name)}: ${JSON.stringify(JSON.stringify(asts.get(name), stripPositions))},`);
// Theme::getImgPath() checks is_readable() per theme, so each theme gets its own image list.
const themeImages = Object.fromEntries(readdirSync(themesDir, { withFileTypes: true })
	.filter(entry => entry.isDirectory())
	.map(entry => entry.name)
	.toSorted(compareCodeUnits)
	.map(theme => [theme, listFiles(path.join(themesDir, theme, 'img'))]));

const moduleSource = [
	'// Generated by scripts/precompile-templates.ts from vendor/phpmyadmin-5.2.3/templates. Do not edit.',
	'export default {',
	'\ttemplates: {',
	...entries,
	'\t},',
	`\tthemeImages: ${JSON.stringify(themeImages)},`,
	'};',
	'',
].join('\n');
const declarationSource = [
	'// Generated by scripts/precompile-templates.ts. Do not edit.',
	'declare const generated: {',
	'\t/** Twing template ASTs as JSON strings, keyed by template name. */',
	'\ttemplates: Record<string, string>;',
	'\t/** Files under public/themes/<theme>/img, keyed by theme id. */',
	'\tthemeImages: Record<string, string[]>;',
	'};',
	'export default generated;',
	'',
].join('\n');

mkdirSync(outputDir, { recursive: true });
writeFileSync(path.join(outputDir, 'twig-templates.js'), moduleSource);
writeFileSync(path.join(outputDir, 'twig-templates.d.ts'), declarationSource);
console.log(`Precompiled ${names.length} templates (${(moduleSource.length / 1024 / 1024).toFixed(1)} MiB) to src/generated/twig-templates.js`);
